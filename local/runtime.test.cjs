const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {createRuntime}=require('./apps-script-runtime.cjs');
const r=createRuntime(),day=r.provenance.asOf,month=day.slice(0,7);
const permission=r.context.getPermissionModel_(false);
const codes=new Set(permission.stations.map(h=>h.hubCode));
const boot=r.call('getWorkspaceBootstrapFast',[true]);
assert.equal(boot.drill.stationCount,codes.size);
assert(codes.size>100);
const monthly=r.call('getKpiClientMonthCache',[month,false]);
assert.equal(monthly.rows.length,codes.size);
assert(monthly.rows.every(row=>codes.has(row.hubCode)));
assert(monthly.rows.some(row=>row.fmOntime.numeric!==null));
const daily=r.call('getDailyKpiClientPeriodCache',[month,false]);
assert(daily.rows.length>=codes.size);
assert(daily.rows.every(row=>codes.has(row[1])&&row[0].startsWith(month)));
const raw=JSON.parse(fs.readFileSync(path.join(__dirname,'workbooks.private.json'),'utf8'));
for(const sheet of ['KPI Daily','KPI Result']){
  const original=raw.frontend.sheets[sheet],prepared=r.data.frontend.sheets[sheet];
  original.forEach((row,i)=>row.forEach((value,j)=>{
    if(value!==''&&value!==null&&typeof value!=='object')assert.equal(prepared[i][j],value,`${sheet} original cell ${i+1},${j+1} changed`);
  }));
}
const snapshot=r.call('getD0Snapshot',[false]);
assert(snapshot.sheets['Roster D0'].length>100);
assert(snapshot.sheets['Attendance Hours D0'].length>100);
for(const rows of Object.values(snapshot.sheets))assert(rows.every(row=>codes.has(row.hub_code)||row.hub_code===undefined));
assert(r.call('getD0Riders',[permission.stations[0].hubCode,1,'driver_name','asc',false,'']).total>=1);
assert(r.call('getHubMap',[]).hubs.some(h=>typeof h.lat==='number'));
const dtc=r.call('getDtcAlerts',[]);
assert(dtc.forecast.dates.length>0);
assert(dtc.hubs.every(h=>h.current&&h.current.value!==null));
assert.equal(dtc.forecast.matchedHubs,codes.size);
assert(r.call('getBacklogEodHistory',[]).rows.length>100);
assert(r.call('getForecastClientMasterCache',[false]).rows.length>100);
assert(r.call('getSourceHealth',[]).sources.length>10);
const request={scopeType:'CITY',scopeValue:'HCM_CITY',anchorDate:day};
const status=r.call('flmTeamGetSourceStatus',[{...request,module:'snapshot'}]);
assert(status.sources.every(s=>!s.latestDate||s.latestDate<=status.closingDate));
const volume=r.call('flmTeamGetVolume',[request]);
assert(volume.found&&volume.series.length>0);
assert(volume.sources.every(s=>s.localMock===true));
const claims=r.call('flmTeamGetClaims',[request]);
assert.equal(claims.claims.urgent.status,'OK');assert.equal(claims.lost.status,'OK');
const sup=Object.values(permission.users).find(u=>u.rank==='SUP'&&u.hubCodes.length<codes.size);
assert(sup);
r.context.Session.getActiveUser=()=>({getEmail:()=>sup.email});
const scoped=r.call('getKpiClientMonthCache',[month,false]);
assert(scoped.rows.length>0&&scoped.rows.length<monthly.rows.length);
assert(scoped.rows.every(row=>sup.hubCodes.includes(row.hubCode)));
const forbidden=permission.stations.find(h=>!sup.hubCodes.includes(h.hubCode));
assert.throws(()=>r.call('getD0Riders',[forbidden.hubCode,1,'driver_name','asc',false,'']));
r.context.Session.getActiveUser=()=>({getEmail:()=>'unknown@example.test'});
assert.throws(()=>r.call('getKpiClientMonthCache',[month,false]));
assert.throws(()=>r.call('getDb_',[]));
console.log('PASS: Excel source values preserved; KPI monthly/daily, D0/riders/hourly attendance, map, DTC/FC, forecast, backlog and source health.');
console.log('PASS: FLM volume/claims/lost mock sources; SUP filtering, unauthorized HUB and unknown account denied.');
